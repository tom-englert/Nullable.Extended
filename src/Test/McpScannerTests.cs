        [Fact]
        public async Task ScanFindsTheOperatorsWithProjectStatusAndContext()
        {
            var scanner = CreateScanner();

            var scan = await scanner.ScanAsync(new ScopeFilter(Project: "A"), TestContext.Current.CancellationToken);

            var items = scan.Occurrences;

            Assert.Collection(items,
                item =>
                {
                    Assert.Equal("A/Foo.cs", item.File);
                    Assert.Equal("A", item.Project);
                    Assert.Equal(5, item.Line);
                    Assert.Equal(FooSource.Split('\n')[4].IndexOf('!') + 1, item.Column);
                    Assert.Equal(NullForgivingContext.NullOrDefault, item.Context);
                    Assert.Equal(Status.Unjustified, item.Status);
                    Assert.Equal("A/Foo.cs:5:" + item.Column, item.Id);
                    Assert.Equal("object _field = null!;", item.SourceLine);
                },
                item =>
                {
                    Assert.Equal(8, item.Line);
                    Assert.Equal(Status.Justified, item.Status);
                    Assert.Equal("the cache always sets it", item.Justification);
                },
                item =>
                {
                    Assert.Equal(11, item.Line);
                    Assert.Equal(Status.Placeholder, item.Status);
                },
                item =>
                {
                    Assert.Equal(13, item.Line);
                    Assert.Equal(NullForgivingContext.Lambda, item.Context);
                    Assert.Equal(Status.Unjustified, item.Status);
                });
        }

        [Fact]

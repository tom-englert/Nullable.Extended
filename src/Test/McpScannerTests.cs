        [Fact]
        public async Task FilesAreOnlyScannedAgainWhenTheyHaveChanged()
        {
            var scanner = CreateScanner();
            var cancellationToken = TestContext.Current.CancellationToken;
            var scope = new ScopeFilter(Project: "B");

            var first = await scanner.ScanAsync(scope, cancellationToken);
            Assert.Equal(1, first.Info.FilesScanned);
            Assert.Single(first.Occurrences);

            var second = await scanner.ScanAsync(scope, cancellationToken);
            Assert.Equal(0, second.Info.FilesScanned);
            Assert.Equal(1, second.Info.FilesFromCache);
            Assert.Single(second.Occurrences);

            WriteFile("B/Sub/Bar.cs", BarSource.Replace("return 0;", "return s!.Length + s!.Length;"));

            var third = await scanner.ScanAsync(scope, cancellationToken);
            Assert.Equal(1, third.Info.FilesScanned);
            Assert.Equal(3, third.Occurrences.Count);
        }


        [Fact]
        public async Task ChangedSinceSelectsChangedAndUntrackedFiles()
        {
            if (!RunGit("--version", out _))
            {
                Assert.Skip("git is not available");
            }

            Assert.True(RunGit("init -q", out var error), error);
            Assert.True(RunGit("add -A", out error), error);
            Assert.True(RunGit("-c user.name=test -c user.email=test@example.com commit -q -m initial", out error), error);

            WriteFile("B/Sub/Bar.cs", BarSource + "\n// changed");
            WriteFile("A/New.cs", "class New { object o = null!; }");

            var scanner = CreateScanner();

            var scan = await scanner.ScanAsync(new ScopeFilter(ChangedSince: "HEAD"), TestContext.Current.CancellationToken);

            Assert.Equal(["A/New.cs", "B/Sub/Bar.cs"], scan.Files.Select(file => file.RelativePath));

            var exception = await Assert.ThrowsAsync<McpException>(() => scanner.ScanAsync(new ScopeFilter(ChangedSince: "does-not-exist"), TestContext.Current.CancellationToken));
            Assert.Contains("does-not-exist", exception.Message);
        }


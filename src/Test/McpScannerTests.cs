        private const string FooSource = """
            namespace A;

            class Foo
            {
                object _field = null!;

                // ! the cache always sets it
                string M1(string? s) => s!;

                // ! TODO:
                int M2(string? s) => s!.Length;

                System.Func<string?, int> M3() => s => s!.Length;
            }
            """;

        private const string BarSource = """
            class Bar
            {
                int M(string? s)
                {
                    if (s != null)
                        return s!.Length;

                    return 0;
                }
            }
            """;

        private static readonly Lazy<IAnalyzerEngine> Engine = new(CreateEngine);

        private readonly string _root = Path.Combine(Path.GetTempPath(), "NullableExtendedMcpTests_" + Guid.NewGuid().ToString("N"));

        public McpScannerTests()
        {
            Directory.CreateDirectory(_root);

            WriteFile("A/A.csproj", "<Project Sdk=\"Microsoft.NET.Sdk\" />");
            WriteFile("A/Foo.cs", FooSource);
            WriteFile("A/Foo.Designer.cs", "class Generated { object o = null!; }");
            WriteFile("A/obj/Debug/Obj.cs", "class Obj { object o = null!; }");
            WriteFile("A/bin/Bin.cs", "class Bin { object o = null!; }");
            WriteFile("A/AutoGenerated.cs", "// <auto-generated>\nclass Auto { object o = null!; }");
            WriteFile("B/B.csproj", "<Project Sdk=\"Microsoft.NET.Sdk\" />");
            WriteFile("B/Sub/Bar.cs", BarSource);
            WriteFile("B/B.AssemblyInfo.cs", "class BAssemblyInfo { object o = null!; }");
            WriteFile("Loose.cs", "class Loose { object o = null!; }");
        }

        public void Dispose()
        {
            try
            {
                foreach (var file in Directory.EnumerateFiles(_root, "*", SearchOption.AllDirectories))
                {
                    File.SetAttributes(file, FileAttributes.Normal);
                }

                Directory.Delete(_root, true);
            }
            catch (IOException)
            {
                // best effort
            }
        }

